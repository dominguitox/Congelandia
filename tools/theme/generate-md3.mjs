import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import {
    argbFromHex, hexFromArgb, Hct, MaterialDynamicColors, SchemeTonalSpot,
} from '@material/material-color-utilities';

const root = fileURLToPath(new URL('../../', import.meta.url));
const roles = [
    'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer',
    'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
    'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
    'error', 'onError', 'errorContainer', 'onErrorContainer',
    'surface', 'surfaceDim', 'surfaceBright', 'surfaceContainerLowest',
    'surfaceContainerLow', 'surfaceContainer', 'surfaceContainerHigh',
    'surfaceContainerHighest', 'onSurface', 'onSurfaceVariant',
    'outline', 'outlineVariant', 'inverseSurface', 'inverseOnSurface',
    'inversePrimary', 'surfaceTint', 'shadow', 'scrim',
];
const kebab = (value) => value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

export function generateMd3() {
    const colors = MaterialDynamicColors;
    const palettes = ['base', 'esmeralda', 'aurora', 'coral'].map((name) => {
        // The existing palette remains the single source of its brand seed.
        const source = name === 'base' ? 'tokens.css' : `themes/${name}.css`;
        const css = readFileSync(resolve(root, 'resources/css/theme', source), 'utf8');
        const seed = css.match(/--color-primary:\s*(#[\da-f]{6})/i)?.[1];
        if (!seed) throw new Error(`No se encontro el color base de ${name}.`);
        // Pin the classic MD3 specification rather than changing with library defaults.
        const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), false, 0);
        const values = Object.fromEntries(roles.map((role) => [kebab(role), hexFromArgb(colors[role].getArgb(scheme))]));
        // Semantic business states use the same tonal algorithm and role pairings.
        for (const [name, seed] of Object.entries({ success: '#16854b', warning: '#946200' })) {
            const semantic = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), false, 0);
            for (const [suffix, role] of Object.entries({ '': 'primary', '-container': 'primaryContainer' })) {
                values[`${name}${suffix}`] = hexFromArgb(colors[role].getArgb(semantic));
                values[`on-${name}${suffix}`] = hexFromArgb(colors[`on${role[0].toUpperCase()}${role.slice(1)}`].getArgb(semantic));
            }
        }
        const declarations = Object.entries(values).flatMap(([role, hex]) => {
            const rgb = [1, 3, 5].map((start) => parseInt(hex.slice(start, start + 2), 16)).join(', ');
            return [`    --md-sys-color-${role}: ${hex};`, `    --md-sys-color-${role}-rgb: ${rgb};`];
        });
        return `:root[data-theme="md3"][data-color="${name}"] {\n${declarations.join('\n')}\n}`;
    });
    return `/* Generated by npm run theme:generate. Do not edit.\n   Material Color Utilities: HCT / Tonal Spot, MD3 2021, light, standard contrast. */\n\n${palettes.join('\n\n')}\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    writeFileSync(resolve(root, 'resources/css/theme/md3-colors.css'), generateMd3());
    console.log('Paletas MD3 generadas: base, esmeralda, aurora y coral.');
}
